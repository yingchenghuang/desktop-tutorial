const assert = require('node:assert/strict');
const taxonomy = require('../assets/archive-taxonomy.js');
const classify = taxonomy.classify;
const artwork = {category:'作品/展覽'};
assert.equal(classify({...artwork, updated:'2026-11-19', collectionDate:'2026-11-19'}).year, null);
assert.equal(classify({...artwork, originalDate:'1992；2020年移除'}).year, 1992);
assert.equal(classify({...artwork, classicTitle:'House', works:'House｜1993–1994'}).year, 1993);
assert.equal(classify({...artwork, works:'reported 2026-04-30; on view through 2026-12-31'}).year, null);
assert.equal(classify({category:'經典作品',classicTitle:'A Logo for America｜1987'}).era,'1980');
assert.equal(classify({category:'全球重要展覽',works:'雙年展｜2024-04-20–2024-11-24'}).year,2024);
const profile=classify({category:'藝術家',media:['雕塑']});
assert.deepEqual(profile.missing,[]);
assert.equal(profile.scope,'profile');
assert.deepEqual(profile.site,['not-applicable']);
assert.equal(profile.era,'not-applicable');
const call=classify({category:'公開徵件',deadline:'2026-12-01',updated:'2026-11-19'});
assert(call.method.includes('open-call'));
assert.equal(call.era,'not-applicable');
assert(call.missing.includes('kind')&&call.missing.includes('site'));
assert(!call.missing.includes('method')&&!call.missing.includes('era'));
const unknown=classify({...artwork,comment:'一件公共藝術作品'});
assert.deepEqual(unknown.method,['unknown']);
assert(unknown.missingReasons.method.includes('未載明'));
assert(unknown.missingReasons.era.includes('更新日不作作品年代'));
assert(classify({...artwork,media:['攝影'],material:'攝影海報'}).kind.includes('photography'));
assert(classify({...artwork,media:['掛毯','纖維藝術']}).kind.includes('textile'));
assert(!classify({...artwork,media:['雕塑'],material:'玻璃纖維'}).kind.includes('textile'));
assert(classify({...artwork,media:['行為/表演']}).kind.includes('performance'));
assert(classify({...artwork,media:['建築整合']}).kind.includes('architecture'));
assert(!classify({...artwork,media:['建築/場域']}).kind.includes('installation'));
assert(classify({...artwork,material:'攝影、文字與交通站亭海報'}).site.includes('transport'));
assert(classify({...artwork,comment:'作品設置於小學校園。'}).site.includes('school'));
assert(classify({...artwork,country:'美國 / Madison Square Park'}).site.includes('park'));
assert.deepEqual(classify({...artwork,country:'美國 / Seattle'}).site,['unknown']);
assert(classify({category:'國際展覽',venue:'GRIMM，Leidsegracht 38-40, Amsterdam'}).site.includes('culture'));
assert.equal(taxonomy.budgetOf({budget:'未公開'}),null);
assert.equal(taxonomy.budgetOf({budget:'NOK 700,000；3名提案者各NOK30,000'}).min,700000);
console.log('PASS evidence-based forms, explicit work years, pending reasons, profile/call applicability, venues and original-currency budgets');
